    'Private Telegram chat used for appointment reminders and status notifications.';

-- One contact per normalized phone/email/chat identity inside a clinic. These
-- indexes are the database guarantee behind the Telegram registration lock.
do $$
begin
    if exists (
        select 1
          from public.contacts
         where phone_number is not null
           and regexp_replace(phone_number, '\D', '', 'g') <> ''
         group by clinic_id, regexp_replace(phone_number, '\D', '', 'g')
        having count(*) > 1
    ) then
        raise exception using
            message = 'Duplicate contact phone numbers exist; resolve them before applying patient identity uniqueness',
            errcode = 'check_violation';
    end if;

    if exists (
        select 1
          from public.contacts
         where email is not null and btrim(email) <> ''
         group by clinic_id, lower(btrim(email))
        having count(*) > 1
    ) then
        raise exception using
            message = 'Duplicate contact emails exist; resolve them before applying patient identity uniqueness',
            errcode = 'check_violation';
    end if;
end;
$$;

create unique index if not exists contacts_clinic_phone_unique
    on public.contacts (clinic_id, regexp_replace(phone_number, '\D', '', 'g'))
    where phone_number is not null and regexp_replace(phone_number, '\D', '', 'g') <> '';

create unique index if not exists contacts_clinic_email_unique
    on public.contacts (clinic_id, lower(btrim(email)))
    where email is not null and btrim(email) <> '';

create unique index if not exists contacts_clinic_telegram_unique
    on public.contacts (clinic_id, telegram_chat_id)
    where telegram_chat_id is not null;

