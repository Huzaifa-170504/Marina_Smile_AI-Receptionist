-- ---------------------------------------------------------------------------
-- Payment gate: cash bookings are confirmed unpaid; online bookings still
-- require a verified payment record.
-- ---------------------------------------------------------------------------
create or replace function private.validate_appointment_write()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
    service_requires_payment boolean;
    request_requires_payment boolean;
    request_has_lines boolean;
    request_row public.booking_requests%rowtype;
    payment_status text;
begin
    if tg_op = 'INSERT' and new.status <> 'pending' then
        raise exception using message = 'A new appointment must start as pending', errcode = 'check_violation';
    end if;

    if tg_op = 'UPDATE' and (
        new.clinic_id is distinct from old.clinic_id
        or new.patient_id is distinct from old.patient_id
        or new.contact_id is distinct from old.contact_id
        or new.booking_request_id is distinct from old.booking_request_id
        or new.payment_id is distinct from old.payment_id
        or new.service_id is distinct from old.service_id
        or new.idempotency_key is distinct from old.idempotency_key
    ) then
        raise exception using message = 'Appointment identity and financial links are immutable', errcode = 'check_violation';
    end if;

    select payment_required
      into service_requires_payment
      from public.services
     where id = new.service_id
       and clinic_id = new.clinic_id;

    if service_requires_payment is null then
        raise exception using message = 'Appointment service is invalid for clinic', errcode = '23503';
    end if;

    if new.booking_request_id is not null then
        select *
          into request_row
          from public.booking_requests
         where id = new.booking_request_id
           and clinic_id = new.clinic_id;

        if not found then
            raise exception using message = 'Booking request is invalid for clinic', errcode = '23503';
        end if;

        if request_row.status not in ('payment_verified', 'awaiting_slot_selection', 'converted_to_appointment')
           and not request_row.payment_exempt then
            raise exception using message = 'Booking request is not payment-cleared', errcode = 'check_violation';
        end if;

        select exists (
            select 1
              from public.booking_request_services as lines
             where lines.clinic_id = new.clinic_id
               and lines.booking_request_id = new.booking_request_id
        ) into request_has_lines;

        if request_has_lines then
            select exists (
                select 1
                  from public.booking_request_services as lines
                  join public.services as service
                    on service.clinic_id = lines.clinic_id
                   and service.id = lines.service_id
                 where lines.clinic_id = new.clinic_id
                   and lines.booking_request_id = new.booking_request_id
                   and service.payment_required
            ) into request_requires_payment;
        else
            request_requires_payment := service_requires_payment;
        end if;
    else
        request_requires_payment := service_requires_payment;
    end if;

    if new.payment_id is not null then
        select status
          into payment_status
          from public.payments
         where id = new.payment_id
           and clinic_id = new.clinic_id;
        if payment_status is distinct from 'verified' then
            raise exception using message = 'Appointment payment is not verified', errcode = 'check_violation';
        end if;
    end if;

    if request_requires_payment
       and (
           new.booking_request_id is null
           or (
               not coalesce(request_row.payment_exempt, false)
               and coalesce(request_row.payment_mode, '') <> 'cash'
               and new.payment_id is null
           )
       ) then
        raise exception using message = 'Payment-required service needs verified payment or cash selection', errcode = 'check_violation';
    end if;

    if tg_op = 'UPDATE' and new.status is distinct from old.status then
        if not (
            (old.status = 'pending' and new.status in ('confirmed', 'cancelled'))
            or (old.status = 'confirmed' and new.status in ('cancelled', 'completed', 'no_show'))
        ) then
            raise exception using
                message = format('Invalid appointment transition: %s -> %s', old.status, new.status),
                errcode = 'check_violation';
        end if;
    end if;

    if new.status = 'cancelled' and new.cancelled_at is null then
        new.cancelled_at := pg_catalog.now();
    end if;
    if new.status = 'completed' and new.completed_at is null then
        new.completed_at := pg_catalog.now();
    end if;
    if new.status = 'confirmed' and nullif(pg_catalog.btrim(new.google_calendar_event_id), '') is null then
        raise exception using message = 'A confirmed appointment requires a Google Calendar event ID', errcode = 'check_violation';
    end if;
    if new.status = 'cancelled' and (
        nullif(pg_catalog.btrim(new.cancellation_reason), '') is null
        or new.cancellation_source is null
    ) then
        raise exception using message = 'A cancelled appointment requires a reason and source', errcode = 'check_violation';
    end if;
    if new.status = 'completed' and new.completed_by_staff_id is null then
        raise exception using message = 'A completed appointment requires the responsible staff member', errcode = 'check_violation';
    end if;

    return new;
end;
$$;

-- ---------------------------------------------------------------------------
-- Reservation and confirmation now carry payment mode and multi-service lines.
-- ---------------------------------------------------------------------------
create or replace function public.reserve_appointment(
    p_clinic_id uuid,
    p_booking_request_id uuid,
    p_payment_id uuid,
    p_dentist_id uuid,
    p_start_at timestamptz,
    p_end_at timestamptz,
    p_idempotency_key uuid
)
returns public.appointments
language plpgsql
security definer
set search_path = ''
as $$
declare
    request_row public.booking_requests%rowtype;
    result public.appointments%rowtype;
    line_count integer;
    unqualified_count integer;
begin
    if not private.is_service_role() then
        raise exception using message = 'Appointment reservation requires the trusted server role', errcode = '42501';
    end if;
    if p_clinic_id is null or p_booking_request_id is null or p_dentist_id is null
       or p_start_at is null or p_end_at is null or p_idempotency_key is null then
        raise exception using message = 'Reservation arguments must not be null', errcode = '22023';
    end if;
    if p_end_at <= p_start_at then
        raise exception using message = 'Appointment end must be later than start', errcode = '22023';
    end if;

    select * into result
      from public.appointments
     where idempotency_key = p_idempotency_key;
    if found then
        if result.clinic_id <> p_clinic_id
           or result.booking_request_id <> p_booking_request_id
           or result.payment_id is distinct from p_payment_id
           or result.dentist_id <> p_dentist_id
           or result.start_at <> p_start_at
           or result.end_at <> p_end_at then
            raise exception using message = 'Idempotency key belongs to another reservation', errcode = '23505';
        end if;
        return result;
    end if;

    select * into request_row
      from public.booking_requests
     where id = p_booking_request_id
       and clinic_id = p_clinic_id
     for update;
    if not found then
        raise exception using message = 'Booking request not found', errcode = 'P0002';
    end if;
    if request_row.status not in ('payment_verified', 'awaiting_slot_selection')
       and not request_row.payment_exempt then
        raise exception using message = 'Booking request is not ready for reservation', errcode = 'check_violation';
    end if;

    select count(*) into line_count
      from public.booking_request_services
     where clinic_id = p_clinic_id
       and booking_request_id = p_booking_request_id;

    if line_count = 0 then
        if not exists (
            select 1
              from public.dentists as d
              join public.dentist_services as ds
                on ds.clinic_id = d.clinic_id
               and ds.dentist_id = d.id
               and ds.service_id = request_row.service_id
             where d.id = p_dentist_id
               and d.clinic_id = p_clinic_id
               and d.active
        ) then
            raise exception using message = 'Dentist is inactive, outside the clinic, or unqualified', errcode = 'check_violation';
        end if;
    else
        select count(*) into unqualified_count
          from public.booking_request_services as lines
         where lines.clinic_id = p_clinic_id
           and lines.booking_request_id = p_booking_request_id
           and not exists (
               select 1
                 from public.dentist_services as ds
                 join public.dentists as d
                   on d.clinic_id = ds.clinic_id
                  and d.id = ds.dentist_id
                where ds.clinic_id = p_clinic_id
                  and ds.dentist_id = p_dentist_id
                  and ds.service_id = lines.service_id
                  and d.active
           );
        if unqualified_count > 0 then
            raise exception using message = 'Dentist does not provide every selected service', errcode = 'check_violation';
        end if;
    end if;

    insert into public.appointments (
        clinic_id, patient_id, contact_id, booking_request_id, payment_id,
        service_id, dentist_id, start_at, end_at, status, idempotency_key,
        payment_mode, payment_status, total_amount, currency
    ) values (
        request_row.clinic_id, request_row.patient_id, request_row.contact_id,
        request_row.id, p_payment_id, request_row.service_id, p_dentist_id,
        p_start_at, p_end_at, 'pending', p_idempotency_key,
        coalesce(request_row.payment_mode, 'online'),
        request_row.payment_status,
        request_row.total_amount,
        coalesce(request_row.currency, 'AED')
    ) returning * into result;

    insert into public.appointment_services (
        clinic_id, appointment_id, service_id, service_name,
        price_amount, duration_minutes, currency
    )
    select lines.clinic_id, result.id, lines.service_id, lines.service_name,
           lines.price_amount, lines.duration_minutes, lines.currency
      from public.booking_request_services as lines
     where lines.clinic_id = p_clinic_id
       and lines.booking_request_id = p_booking_request_id
    on conflict (clinic_id, appointment_id, service_id) do nothing;

    if line_count = 0 then
        insert into public.appointment_services (
            clinic_id, appointment_id, service_id, service_name,
            price_amount, duration_minutes, currency
        )
        select result.clinic_id, result.id, service.id, service.name,
               coalesce(service.price_from, 0), service.duration_minutes, service.currency
          from public.services as service
         where service.clinic_id = result.clinic_id
           and service.id = result.service_id
        on conflict (clinic_id, appointment_id, service_id) do nothing;
    end if;

    return result;
end;
$$;

-- Cash payments are collected at the clinic. This records the settled state
-- without inventing an online proof.
create or replace function public.mark_cash_payment_paid(p_appointment_id uuid)
returns public.appointments
language plpgsql
security definer
set search_path = ''
as $$
declare
    actor_id uuid := private.current_staff_id();
    appointment_row public.appointments%rowtype;
begin
    if actor_id is null or not private.has_permission('payment.verify') then
        raise exception using message = 'Cash payment confirmation is not authorized', errcode = '42501';
    end if;

    select * into appointment_row
      from public.appointments
     where id = p_appointment_id
       and clinic_id = private.current_clinic_id()
     for update;
    if not found then
        raise exception using message = 'Appointment not found', errcode = 'P0002';
    end if;
    if appointment_row.payment_mode is distinct from 'cash' then
        raise exception using message = 'Only a cash appointment can be marked paid here', errcode = 'check_violation';
    end if;
    if appointment_row.payment_status = 'paid' then
        return appointment_row;
    end if;

    update public.booking_requests
       set payment_status = 'paid'
     where id = appointment_row.booking_request_id
       and clinic_id = appointment_row.clinic_id;

    if not exists (
        select 1
          from public.payments
         where clinic_id = appointment_row.clinic_id
           and booking_request_id = appointment_row.booking_request_id
           and method = 'cash'
    ) then
        insert into public.payments (
            clinic_id, booking_request_id, patient_id, amount_expected,
            amount_verified, currency, status, method, verified_by_staff_id,
            verified_at, submission_idempotency_key
        ) values (
            appointment_row.clinic_id, appointment_row.booking_request_id,
            appointment_row.patient_id,
            coalesce(appointment_row.total_amount, 0),
            coalesce(appointment_row.total_amount, 0),
            coalesce(appointment_row.currency, 'AED'),
            'verified', 'cash', actor_id, pg_catalog.now(), gen_random_uuid()
        );
    end if;

    update public.appointments
       set payment_status = 'paid'
     where id = appointment_row.id
    returning * into appointment_row;

    return appointment_row;
end;
$$;

-- ---------------------------------------------------------------------------
-- Served reconciliation: appointments whose end time has passed and that
-- never entered the queue stop blocking the patient from booking again.
-- ---------------------------------------------------------------------------
create or replace function public.mark_due_appointments_served(p_grace_minutes integer default 30)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
    cutoff timestamptz;
    served_count integer;
begin
    if not private.is_service_role() then
        raise exception using message = 'Served reconciliation requires the trusted server role', errcode = '42501';
    end if;
    if p_grace_minutes is null or p_grace_minutes < 0 or p_grace_minutes > 1440 then
        raise exception using message = 'Grace minutes must be between 0 and 1440', errcode = '22023';
    end if;

    cutoff := pg_catalog.now() - pg_catalog.make_interval(mins => p_grace_minutes);

    with candidates as (
        select appointment.id, appointment.clinic_id
          from public.appointments as appointment
          left join public.appointment_visits as visit
            on visit.appointment_id = appointment.id
         where appointment.status = 'confirmed'
           and appointment.end_at <= cutoff
           and (visit.id is null or visit.queue_status = 'scheduled')
    ),
    updated_visits as (
        update public.appointment_visits as visit
           set queue_status = 'no_show'
          from candidates
         where visit.appointment_id = candidates.id
           and visit.queue_status = 'scheduled'
        returning visit.appointment_id
    )
    update public.appointments as appointment
       set status = 'no_show'
      from candidates
     where appointment.id = candidates.id
       and appointment.status = 'confirmed';

    get diagnostics served_count = row_count;

    update public.outbound_notifications as notification
       set status = 'cancelled'
      from public.appointments as appointment
     where notification.appointment_id = appointment.id
       and notification.status = 'pending'
       and appointment.status = 'no_show'
       and appointment.end_at <= cutoff;

    return served_count;
end;
$$;

revoke all on function public.mark_cash_payment_paid(uuid)
    from public, anon, authenticated, service_role;
revoke all on function public.mark_due_appointments_served(integer)
    from public, anon, authenticated, service_role;
revoke all on function public.reserve_appointment(uuid, uuid, uuid, uuid, timestamptz, timestamptz, uuid)
    from public, anon, authenticated, service_role;

grant execute on function public.mark_cash_payment_paid(uuid) to authenticated;
grant execute on function public.mark_due_appointments_served(integer) to service_role;
grant execute on function public.reserve_appointment(uuid, uuid, uuid, uuid, timestamptz, timestamptz, uuid) to service_role;

commit;
