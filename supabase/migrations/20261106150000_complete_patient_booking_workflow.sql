create or replace function private.manage_patient_number()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
    sequence_value bigint;
begin
    if tg_op = 'UPDATE' then
        if new.patient_number is distinct from old.patient_number then
            raise exception using
                message = 'Patient number is immutable',
                errcode = 'check_violation';
        end if;
        return new;
    end if;

    if new.patient_number is null or pg_catalog.btrim(new.patient_number) = '' then
        sequence_value := pg_catalog.nextval('private.patient_number_seq'::regclass);
        new.patient_number := pg_catalog.format(
            'MS-P-%s',
            pg_catalog.lpad(sequence_value::text, 6, '0')
        );
    end if;
    return new;
end;
$$;

revoke all on function private.manage_patient_number()
    from public, anon, authenticated, service_role;

drop trigger if exists patients_manage_number on public.patients;
create trigger patients_manage_number
before insert or update of patient_number on public.patients
for each row execute function private.manage_patient_number();

