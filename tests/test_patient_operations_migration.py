def test_all_security_definer_functions_fix_search_path_and_revoke_public_execution() -> None:
    sql = _sql()
    function_chunks = sql.split("create or replace function ")[1:]
    for chunk in function_chunks:
        header_and_body = chunk.split("$$;", 1)[0]
        if "security definer" in header_and_body:
            assert "set search_path = ''" in header_and_body
    assert "revoke all on function public.request_refund" in sql
    assert "revoke all on function public.check_in_appointment" in sql
    assert "revoke all on function public.transition_queue_state" in sql
    assert " to anon" not in sql


